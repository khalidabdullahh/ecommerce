// Generates db/seed.sql from src/data/initialProducts.ts  (run: npm run db:seed:generate)
import fs from "node:fs";
import ts from "typescript";

const src = fs.readFileSync("src/data/initialProducts.ts", "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
new Function("exports", "module", "require", js)(mod.exports, mod, () => ({}));
const products = mod.exports.initialProducts;

const q = (v) => (v === undefined || v === null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => q(JSON.stringify(v ?? []));
const now = new Date().toISOString();

const lines = ["-- Generated by scripts/generate-seed.mjs. Safe to re-run (INSERT OR IGNORE).", ""];
products.forEach((p, i) => {
  lines.push(
    `INSERT OR IGNORE INTO products (id, title, bangla_title, category, price, original_price, rating, sold_count, images, description, sizes, colors, is_featured, is_popular, in_stock, tags, sort_order, created_at) VALUES (` +
      [q(p.id), q(p.title), q(p.banglaTitle), q(p.category), p.price, p.originalPrice ?? "NULL", p.rating, q(p.soldCount), j(p.images), q(p.description), j(p.sizes), j(p.colors),
       p.isFeatured ? 1 : 0, p.isPopular ? 1 : 0, p.inStock ? 1 : 0, j(p.tags), products.length - i, q(now)].join(", ") + `);`
  );
});
fs.writeFileSync("db/seed.sql", lines.join("\n") + "\n");
console.log(`db/seed.sql: ${products.length} products`);
